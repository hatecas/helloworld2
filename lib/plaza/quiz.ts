/* 한 라운드의 흐름                                                     */
/* ================================================================== */

/**
 * 문제가 떠 있고 O/X 로 옮겨 갈 수 있는 시간(ms).
 *
 * 퀴즈장 이동 속도(380px/s)로 한가운데서 칸까지는 0.3~0.7초, 칸에서 반대편 칸까지는
 * 1.05초 걸린다. 6초면 읽고 고르고도 한 번쯤 마음을 바꿀 여유가 남는다.
 */
export const QUIZ_ASK_MS = 6_000;
/** 정답을 보여 주고 채점 결과가 머리 위에 뜨는 시간(ms) */
export const QUIZ_REVEAL_MS = 3_000;
/** 한 문제가 도는 데 걸리는 시간(ms) */
export const QUIZ_ROUND_MS = QUIZ_ASK_MS + QUIZ_REVEAL_MS;

export type QuizPhase = 'ask' | 'reveal';

export interface QuizItem {
  /** 문제 (O 인지 X 인지 판단할 한 문장) */
  q: string;
  /** 정답. true 면 O */
  a: boolean;
  /** 정답 공개 때 같이 보여 주는 한 줄 설명 */
  note: string;
}

export interface QuizRound {
  /** 라운드 번호 — 벽시계에서 바로 나오므로 모두의 값이 같다 */
  index: number;
  item: QuizItem;
  phase: QuizPhase;
  /** 지금 단계가 끝나기까지 남은 시간(ms) */
  leftMs: number;
  /** 지금 단계의 전체 길이(ms) — 남은 시간 막대를 그릴 때 쓴다 */
  spanMs: number;
}

/* ================================================================== */
/* O · X 칸                                                            */
/* ================================================================== */

/**
 * 답을 고르는 칸. 발(캐릭터의 x, y)이 이 상자 안에 들어와 있으면 그 답을 고른 것이다.
 * (x, y) 는 상자 중심, w/h 는 크기 — 전부 퀴즈장의 논리 좌표(1000 x 500)다.
 *
 * 두 칸을 좌우 끝에 멀찍이 떼어 놓았다. 가운데 400px(이동 속도 380px/s 로 1.05초)을
 * 비워 둬야 갈아타는 데 마음먹을 시간이 들고, 경계에 어정쩡하게 선 사람이
 * 화면마다 다르게 채점되는 일도 없다.
 */
export interface QuizZone {
  /** 이 칸이 뜻하는 답 */
  answer: boolean;
  mark: string;
  label: string;
  x: number;
  y: number;
  w: number;
  h: number;
}

export const QUIZ_ZONES: QuizZone[] = [
  { answer: true, mark: 'O', label: '맞아요', x: 180, y: 320, w: 240, h: 200 },
  { answer: false, mark: 'X', label: '아니에요', x: 820, y: 320, w: 240, h: 200 },
];

/** 이 자리는 어느 칸인가. 아무 칸에도 없으면 null (= 이번 판은 쉬는 중) */
export function zoneAt(x: number, y: number): QuizZone | null {
  for (const z of QUIZ_ZONES) {
    if (Math.abs(x - z.x) <= z.w / 2 && Math.abs(y - z.y) <= z.h / 2) return z;
  }
  return null;
}

