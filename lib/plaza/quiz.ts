/* 몇 번째 라운드에 어떤 문제가 나오는가                                  */
/* ================================================================== */

function gcd(a: number, b: number): number {
  return b === 0 ? a : gcd(b, a % b);
}

/**
 * 문제를 고르는 걸음.
 *
 * 라운드마다 아무 문제나 뽑으면(해시 % 개수) 방금 본 문제가 곧바로 또 나온다.
 * 문제 수와 서로소인 걸음으로 한 칸씩 건너뛰면 **연달아 몇 라운드를 보든**
 * 문제 수만큼(= 지금은 53판, 8분)은 같은 문제가 다시 나오지 않는다.
 */
const STRIDE = (() => {
  const n = QUIZ_BANK.length;
  for (let s = Math.floor(n / 2); s > 1; s--) if (gcd(s, n) === 1) return s;
  return 1;
})();

/** 정수 하나를 골고루 흩뜨린다 (날마다 시작점을 옮기는 데 쓴다) */
function scatter(n: number): number {
  let h = (n + 0x9e3779b9) >>> 0;
  h = Math.imul(h ^ (h >>> 16), 0x45d9f3b) >>> 0;
  h = Math.imul(h ^ (h >>> 16), 0x45d9f3b) >>> 0;
  return (h ^ (h >>> 16)) >>> 0;
}

/** 하루에 도는 라운드 수 */
const ROUNDS_PER_DAY = Math.floor(86_400_000 / QUIZ_ROUND_MS);

/**
 * 이 순서는 벽시계에 매여 있어서, 시작점을 고정해 두면 매일 같은 시각에 같은 문제가
 * 나온다(늘 저녁에 들르는 사람에게는 그게 그대로 보인다). 그래서 날마다 한 번씩
 * 시작점을 옮긴다.
 *
 * 옮기는 지점에서는 위의 '겹치지 않는다' 가 한 번 끊긴다 — 하루에 한 번, 그 언저리에서만
 * 같은 문제가 조금 이르게 다시 나올 수 있다. 순서를 더 자주 섞으면 그만큼 자주 끊기므로
 * (등차로 도는 것 말고는 겹치지 않게 만들 방법이 없다) 하루에 한 번으로 잡았다.
 */
function itemFor(round: number): QuizItem {
  const n = QUIZ_BANK.length;
  const day = Math.floor(round / ROUNDS_PER_DAY);
  return QUIZ_BANK[(round * STRIDE + scatter(day)) % n];
}

/** 이 시각의 라운드. 벽시계만 있으면 되므로 누구 화면에서 불러도 같은 값이 나온다. */
export function quizAt(now: number): QuizRound {
  const index = Math.floor(now / QUIZ_ROUND_MS);
  const into = now - index * QUIZ_ROUND_MS;
  const asking = into < QUIZ_ASK_MS;
  return {
    index,
    item: itemFor(index),
    phase: asking ? 'ask' : 'reveal',
    leftMs: asking ? QUIZ_ASK_MS - into : QUIZ_ROUND_MS - into,
    spanMs: asking ? QUIZ_ASK_MS : QUIZ_REVEAL_MS,
  };
}
