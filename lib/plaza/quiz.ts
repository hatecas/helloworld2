/**
 * 광장 OX 퀴즈.
 *
 * 인내의 숲 방해물(maps.ts 의 Hazard)과 같은 방식이다 — 지금 몇 번째 문제이고
 * 남은 시간이 얼마인지를 오직 벽시계(Date.now)의 함수로 정한다. 문제를 뿌려 주는
 * 서버도, 판을 여는 방장도 없고, 늦게 들어온 사람도 곧바로 같은 문제를 같은 초에 본다.
 *
 * 채점도 각자 자기 화면에서 한다. 정답은 모두가 알고 있고 남이 어디 서 있는지도
 * 좌표(pos)로 이미 알고 있으므로, 신호를 하나도 주고받지 않아도 '누가 맞혔나' 까지
 * 모두 같은 결과가 나온다. 그래서 이 놀이는 통신 코드가 한 줄도 없다.
 *
 * 대신 정답이 이 파일에 그대로 들어 있어서 개발자 도구를 열면 미리 볼 수 있다.
 * 서버가 정답을 뒤늦게 내려 주는 식으로 막을 수는 있지만, 그러면 이 놀이의 장점인
 * '서버 없이 모두가 같은 화면' 이 통째로 깨진다. 미니홈피 광장의 놀이라 열어 두었다.
 */

